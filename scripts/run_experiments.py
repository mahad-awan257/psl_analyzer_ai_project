"""Run the full evaluation and write results/ (CSV tables, charts, RESULTS.md).

Usage:  python scripts/run_experiments.py [--quick] [--no-ablation]
  --quick        3 GA seeds, 5 s limit (smoke test, a few minutes)
  --no-ablation  skip the backtracking run without the Lagrangian bound
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pandas as pd  # noqa: E402

from psl_selector import config as C  # noqa: E402
from psl_selector.dataset import PlayerDataset  # noqa: E402
from psl_selector.experiments import ExperimentRunner, GA_SEEDS  # noqa: E402


def write_markdown(summary: pd.DataFrame, results: pd.DataFrame, path: Path):
    cases = (results[results.method == "Backtracking"]
             [["case_id", "pool_size", "budget", "note", "status", "score", "runtime_s", "exact_optimum"]])
    ga = results[results.method == "Genetic"].groupby("case_id").score.agg(["mean", "std", "min", "max"])
    gr = results[results.method == "Greedy"].set_index("case_id").score
    cases = cases.set_index("case_id").join(ga.add_prefix("ga_")).assign(greedy=gr).reset_index()
    with open(path, "w") as f:
        f.write("# Experiment results\n\nGenerated by `scripts/run_experiments.py`.\n\n")
        f.write("## Summary by method\n\n" + summary.to_markdown() + "\n\n")
        f.write("## Per test case\n\n" + cases.round(3).to_markdown(index=False) + "\n\n")
        f.write("Figures: `results/figures/`.\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--no-ablation", action="store_true")
    a = ap.parse_args()
    ds = PlayerDataset()
    runner = ExperimentRunner(ds, time_limit=5 if a.quick else C.TIME_LIMIT_S,
                              ga_seeds=GA_SEEDS[:3] if a.quick else GA_SEEDS, ablation=not a.no_ablation)
    results, histories = runner.run()
    C.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    results.to_csv(C.RESULTS_DIR / "experiment_results.csv", index=False)
    histories.to_csv(C.RESULTS_DIR / "ga_history.csv", index=False)
    summary = runner.summarise(results)
    summary.to_csv(C.RESULTS_DIR / "summary.csv")
    runner.plot(results, histories, ds.df)
    write_markdown(summary, results, C.RESULTS_DIR / "RESULTS.md")
    pd.set_option("display.width", 200)
    print(summary.to_string())
