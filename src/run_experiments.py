"""Run the whole evaluation with fixed seeds and write outputs/ (tables, charts, RESULTS.md).

Usage:  python src/run_experiments.py [--quick] [--no-ablation]
  --quick        3 GA seeds and a 5 s limit, written to outputs/quick/ so the full results are kept
  --no-ablation  skip the backtracking run without the Lagrangian bound
"""
import argparse
import sys
from pathlib import Path

import pandas as pd

from psl_selector import config as C
from psl_selector import eda
from psl_selector.clustering import compare_models
from psl_selector.dataset import PlayerDataset
from psl_selector.experiments import ExperimentRunner, GA_SEEDS


def write_markdown(summary: pd.DataFrame, results: pd.DataFrame, path: Path) -> None:
    """Write the summary and per-case tables as Markdown."""
    cases = (results[results.method == "Backtracking"]
             [["case_id", "pool_size", "budget", "note", "status", "score", "runtime_s", "exact_optimum"]])
    ga = results[results.method == "Genetic"].groupby("case_id").score.agg(["mean", "std", "min", "max"])
    gr = results[results.method == "Greedy"].set_index("case_id").score
    cases = cases.set_index("case_id").join(ga.add_prefix("ga_")).assign(greedy=gr).reset_index()
    with open(path, "w", encoding="utf-8") as f:
        f.write("# Experiment results\n\nGenerated by `src/run_experiments.py`.\n\n")
        f.write("## Summary by method (solvable cases)\n\n" + summary.to_markdown() + "\n\n")
        f.write("## Per test case\n\n" + cases.round(3).to_markdown(index=False) + "\n\n")
        f.write("Figures: `outputs/figures/`.\n")


def main() -> int:
    """Run EDA, the clustering comparison and all selectors. Returns a process exit code."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--no-ablation", action="store_true")
    a = ap.parse_args()
    out = C.OUTPUTS_DIR / "quick" if a.quick else C.OUTPUTS_DIR
    results_dir, figures_dir = out / "results", out / "figures"
    results_dir.mkdir(parents=True, exist_ok=True)
    try:
        ds = PlayerDataset()
        print("\n".join(eda.run(ds.df, results_dir, figures_dir)))
    except FileNotFoundError as err:
        print(f"Data not ready: {err}", file=sys.stderr)
        return 1
    compare_models(ds.df, int(ds.df.cluster.nunique())).to_csv(results_dir / "cluster_models.csv", index=False)
    runner = ExperimentRunner(ds, time_limit=5 if a.quick else C.TIME_LIMIT_S,
                              ga_seeds=GA_SEEDS[:3] if a.quick else GA_SEEDS, ablation=not a.no_ablation)
    results, histories = runner.run()
    results.to_csv(results_dir / "experiment_results.csv", index=False)
    histories.to_csv(results_dir / "ga_history.csv", index=False)
    summary = runner.summarise(results)
    summary.to_csv(results_dir / "summary.csv")
    runner.plot(results, histories, ds.df, figures_dir)
    write_markdown(summary, results, results_dir / "RESULTS.md")
    pd.set_option("display.width", 200)
    print(summary.to_string())
    return 0


if __name__ == "__main__":
    sys.exit(main())
